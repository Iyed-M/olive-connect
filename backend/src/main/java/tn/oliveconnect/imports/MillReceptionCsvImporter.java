package tn.oliveconnect.imports;

import java.io.IOException;
import java.nio.file.Path;
import java.time.Duration;
import java.time.Instant;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.Set;
import java.util.stream.Collectors;
import org.springframework.data.mongodb.core.BulkOperations.BulkMode;
import org.springframework.data.mongodb.core.MongoTemplate;
import org.springframework.data.mongodb.core.query.Criteria;
import org.springframework.data.mongodb.core.query.Query;
import org.springframework.stereotype.Component;
import tn.oliveconnect.mill.Mill;
import tn.oliveconnect.mill.MillReception;
import tn.oliveconnect.mill.MillRepository;
import tn.oliveconnect.mill.QualityAssessment;
import tn.oliveconnect.mill.QualityGrade;
import tn.oliveconnect.user.Delegation;

/** Imports the historical reception facts generated by data-simulator (one CSV file per season). */
@Component
public class MillReceptionCsvImporter implements DatasetImporter<MillReceptionCsvImporter.ReceptionLine> {

    private static final List<String> COLUMNS = List.of(
            "millId", "roundId", "binId", "orchardId", "farmerId", "harvestRequestId", "grossWeightKg", "tareKg",
            "netWeightKg", "binCapacityKg", "fillRate", "qualityGrade", "defectRatePct", "leafRatePct",
            "estimatedOilYieldPct", "season", "varietyCode", "delegation", "orchardAreaHa", "requestValidatedAt",
            "leadTimeHours", "receivedAt", "receivedById");

    private static final double MAX_BIN_FILL_RATE = 1.15;
    private static final double NUMBER_TOLERANCE = 0.01;

    public record ReceptionLine(
            String millId,
            String roundId,
            String binId,
            String orchardId,
            String farmerId,
            String harvestRequestId,
            double grossWeightKg,
            double tareKg,
            double netWeightKg,
            double binCapacityKg,
            double fillRate,
            QualityGrade qualityGrade,
            double defectRatePct,
            double leafRatePct,
            double estimatedOilYieldPct,
            String season,
            String varietyCode,
            String delegation,
            double orchardAreaHa,
            Instant requestValidatedAt,
            double leadTimeHours,
            Instant receivedAt,
            String receivedById) {
    }

    private final MongoTemplate mongoTemplate;
    private final MillRepository millRepository;

    public MillReceptionCsvImporter(MongoTemplate mongoTemplate, MillRepository millRepository) {
        this.mongoTemplate = mongoTemplate;
        this.millRepository = millRepository;
    }

    @Override
    public String dataset() {
        return "RECEPTIONS";
    }

    @Override
    public ImportSource source() {
        return ImportSource.DYNAMIC;
    }

    @Override
    public boolean accepts(String fileName) {
        return fileName.matches("receptions_\\d{8}\\.csv");
    }

    @Override
    public ParseResult<ReceptionLine> parse(Path file) throws IOException {
        CsvFile.Content csv = CsvFile.read(file, COLUMNS);
        List<ImportError> errors = new ArrayList<>(csv.errors());
        List<Row<ReceptionLine>> rows = new ArrayList<>();
        for (CsvFile.Line line : csv.lines()) {
            FieldReader reader = new FieldReader(line.number(), line.values()::get);
            String qualityText = reader.text("qualityGrade");
            QualityGrade quality = null;
            ImportError qualityError = null;
            if (reader.error() == null) {
                try {
                    quality = QualityGrade.valueOf(qualityText);
                } catch (IllegalArgumentException e) {
                    qualityError = new ImportError(line.number(), "qualityGrade",
                            "'" + qualityText + "' is not a known quality grade");
                }
            }
            ReceptionLine reception = new ReceptionLine(
                    reader.text("millId"),
                    reader.text("roundId"),
                    reader.text("binId"),
                    reader.text("orchardId"),
                    reader.text("farmerId"),
                    reader.text("harvestRequestId"),
                    reader.decimal("grossWeightKg"),
                    reader.decimal("tareKg"),
                    reader.decimal("netWeightKg"),
                    reader.decimal("binCapacityKg"),
                    reader.decimal("fillRate"),
                    quality,
                    reader.decimal("defectRatePct"),
                    reader.decimal("leafRatePct"),
                    reader.decimal("estimatedOilYieldPct"),
                    reader.text("season"),
                    reader.text("varietyCode"),
                    reader.text("delegation"),
                    reader.decimal("orchardAreaHa"),
                    reader.instant("requestValidatedAt"),
                    reader.decimal("leadTimeHours"),
                    reader.instant("receivedAt"),
                    reader.text("receivedById"));
            if (reader.error() != null) {
                errors.add(reader.error());
            } else if (qualityError != null) {
                errors.add(qualityError);
            } else {
                rows.add(new Row<>(line.number(), reception));
            }
        }
        return new ParseResult<>(rows, errors);
    }

    @Override
    public Optional<ImportError> validate(Row<ReceptionLine> row) {
        ReceptionLine reception = row.value();
        int line = row.line();
        if (reception.grossWeightKg() <= 0) {
            return Optional.of(new ImportError(line, "grossWeightKg",
                    reception.grossWeightKg() + " must be greater than 0"));
        }
        if (reception.tareKg() < 0) {
            return Optional.of(new ImportError(line, "tareKg", reception.tareKg() + " is negative"));
        }
        if (reception.netWeightKg() <= 0) {
            return Optional.of(new ImportError(line, "netWeightKg",
                    reception.netWeightKg() + " must be greater than 0"));
        }
        if (reception.binCapacityKg() <= 0) {
            return Optional.of(new ImportError(line, "binCapacityKg",
                    reception.binCapacityKg() + " must be greater than 0"));
        }
        if (reception.fillRate() < 0 || reception.fillRate() > MAX_BIN_FILL_RATE) {
            return Optional.of(new ImportError(line, "fillRate",
                    reception.fillRate() + " is outside 0-" + MAX_BIN_FILL_RATE));
        }
        if (Math.abs(reception.grossWeightKg() - reception.tareKg() - reception.netWeightKg()) > NUMBER_TOLERANCE) {
            return Optional.of(new ImportError(line, "netWeightKg", "does not equal grossWeightKg - tareKg"));
        }
        if (Math.abs(reception.netWeightKg() / reception.binCapacityKg() - reception.fillRate()) > NUMBER_TOLERANCE) {
            return Optional.of(new ImportError(line, "fillRate", "does not equal netWeightKg / binCapacityKg"));
        }
        if (reception.qualityGrade() == null) {
            return Optional.of(new ImportError(line, "qualityGrade", "is missing"));
        }
        if (outsidePercentRange(reception.defectRatePct())) {
            return Optional.of(new ImportError(line, "defectRatePct", "is outside 0-100"));
        }
        if (outsidePercentRange(reception.leafRatePct())) {
            return Optional.of(new ImportError(line, "leafRatePct", "is outside 0-100"));
        }
        if (outsidePercentRange(reception.estimatedOilYieldPct())) {
            return Optional.of(new ImportError(line, "estimatedOilYieldPct", "is outside 0-100"));
        }
        if (!reception.season().matches("\\d{4}-\\d{4}")) {
            return Optional.of(new ImportError(line, "season", "must use YYYY-YYYY"));
        }
        if (reception.varietyCode().isBlank()) {
            return Optional.of(new ImportError(line, "varietyCode", "is missing"));
        }
        try {
            Delegation.valueOf(reception.delegation());
        } catch (IllegalArgumentException e) {
            return Optional.of(new ImportError(line, "delegation", "'" + reception.delegation() + "' is unknown"));
        }
        if (reception.orchardAreaHa() <= 0) {
            return Optional.of(new ImportError(line, "orchardAreaHa",
                    reception.orchardAreaHa() + " must be greater than 0"));
        }
        if (reception.receivedAt().isAfter(Instant.now().plus(Duration.ofHours(1)))) {
            return Optional.of(new ImportError(line, "receivedAt", "is in the future"));
        }
        if (reception.requestValidatedAt().isAfter(reception.receivedAt())) {
            return Optional.of(new ImportError(line, "requestValidatedAt", "is after receivedAt"));
        }
        double expectedLeadTime = Math.max(0,
                Duration.between(reception.requestValidatedAt(), reception.receivedAt()).toMillis() / 3_600_000.0);
        if (Math.abs(expectedLeadTime - reception.leadTimeHours()) > NUMBER_TOLERANCE) {
            return Optional.of(new ImportError(line, "leadTimeHours",
                    "does not match the validation and reception timestamps"));
        }
        return Optional.empty();
    }

    @Override
    public List<ImportError> findDuplicates(List<Row<ReceptionLine>> validRows) {
        if (validRows.isEmpty()) {
            return List.of();
        }
        Set<String> rounds = validRows.stream().map(row -> row.value().roundId()).collect(Collectors.toSet());
        Set<String> bins = validRows.stream().map(row -> row.value().binId()).collect(Collectors.toSet());
        Set<String> orchards = validRows.stream().map(row -> row.value().orchardId()).collect(Collectors.toSet());
        Set<String> seen = new HashSet<>();
        mongoTemplate.find(Query.query(Criteria.where("roundId").in(rounds)
                        .and("binId").in(bins).and("orchardId").in(orchards)), MillReception.class)
                .forEach(stored -> seen.add(key(stored.getRoundId(), stored.getBinId(), stored.getOrchardId())));

        List<ImportError> errors = new ArrayList<>();
        for (Row<ReceptionLine> row : validRows) {
            ReceptionLine reception = row.value();
            if (!seen.add(key(reception.roundId(), reception.binId(), reception.orchardId()))) {
                errors.add(new ImportError(row.line(), "roundId", "duplicate reception key"));
            }
        }
        return errors;
    }

    @Override
    public PersistResult persist(List<ReceptionLine> records) {
        if (records.isEmpty()) {
            return new PersistResult(0, 0);
        }
        Map<String, String> millIds = millRepository.findAllByCodeIn(records.stream()
                        .map(ReceptionLine::millId).distinct().toList()).stream()
                .collect(Collectors.toMap(Mill::getCode, Mill::getId));
        List<MillReception> receptions = records.stream().map(record -> toEntity(record, millIds)).toList();
        int inserted = mongoTemplate.bulkOps(BulkMode.UNORDERED, MillReception.class)
                .insert(receptions).execute().getInsertedCount();
        return new PersistResult(inserted, 0);
    }

    private MillReception toEntity(ReceptionLine record, Map<String, String> millIds) {
        MillReception reception = new MillReception();
        // History files use the stable mills.json code; live weighing already stores the Mongo id.
        reception.setMillId(millIds.getOrDefault(record.millId(), record.millId()));
        reception.setRoundId(record.roundId());
        reception.setBinId(record.binId());
        reception.setOrchardId(record.orchardId());
        reception.setFarmerId(record.farmerId());
        reception.setHarvestRequestId(record.harvestRequestId());
        reception.setGrossWeightKg(record.grossWeightKg());
        reception.setTareKg(record.tareKg());
        reception.setBinCapacityKg(record.binCapacityKg());
        reception.setQuality(toQuality(record));
        reception.setSeason(record.season());
        reception.setVarietyCode(record.varietyCode());
        reception.setDelegation(record.delegation());
        reception.setOrchardAreaHa(record.orchardAreaHa());
        reception.setRequestValidatedAt(record.requestValidatedAt());
        reception.setLeadTimeHours(record.leadTimeHours());
        reception.setReceivedAt(record.receivedAt());
        reception.setReceivedById(record.receivedById());
        reception.computeNetAndFillRate();
        return reception;
    }

    private static QualityAssessment toQuality(ReceptionLine record) {
        QualityAssessment quality = new QualityAssessment();
        quality.setGrade(record.qualityGrade());
        quality.setDefectRatePct(record.defectRatePct());
        quality.setLeafRatePct(record.leafRatePct());
        quality.setEstimatedOilYieldPct(record.estimatedOilYieldPct());
        return quality;
    }

    private static boolean outsidePercentRange(double value) {
        return value < 0 || value > 100;
    }

    private static String key(String roundId, String binId, String orchardId) {
        return roundId + "|" + binId + "|" + orchardId;
    }
}
